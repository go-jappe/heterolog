package s3

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"net/url"
	"strings"

	"github.com/go-jappe/heterolog/pkg/objectstorage"
	"github.com/go-jappe/heterolog/pkg/objectstorage/uploader"
)

const destinationIDPrefix = "s3-"

// ResolveDestinationIDs validates all destinations and returns their IDs in
// configuration order. It rejects destinations whose IDs collide, such as the
// same storage location specified with only different credentials.
func ResolveDestinationIDs(configs []objectstorage.S3Config) ([]objectstorage.DestinationID, error) {
	if len(configs) == 0 {
		return nil, fmt.Errorf("s3 destinations are required")
	}
	ids := make([]objectstorage.DestinationID, 0, len(configs))
	seen := make(map[objectstorage.DestinationID]struct{}, len(configs))
	for index, cfg := range configs {
		if err := ValidateConfig(cfg); err != nil {
			return nil, fmt.Errorf("s3 destination at index %d: %w", index, err)
		}
		id, err := ResolveDestinationID(cfg)
		if err != nil {
			return nil, fmt.Errorf("s3 destination at index %d: %w", index, err)
		}
		if _, exists := seen[id]; exists {
			return nil, fmt.Errorf("s3 destination at index %d: %w", index, uploader.ErrDuplicateDestinationID)
		}
		seen[id] = struct{}{}
		ids = append(ids, id)
	}
	return ids, nil
}

// ResolveDestinationID generates a stable identity from the values that
// determine the actual S3 storage location. It includes the endpoint, the
// region, the bucket, and the prefix that the object keys actually use.
// The credentials, the timeout and force-path-style are settings of the
// delivery method, and they are left out of the identity so that checkpoints
// for the same object namespace can continue.
//
// The identity is generated by encoding Provider, Endpoint, Region, Bucket and
// Prefix into a JSON object in this field order and converting the SHA-256 of
// those bytes to lowercase hexadecimal. The values are normalized as follows.
//
//   - Provider: `s3`
//   - Endpoint: leading and trailing white space is removed, the default
//     endpoint is filled in, trailing slashes are removed from the path, and
//     the scheme and the host are lowercased. An endpoint that contains a
//     query or a fragment is rejected, as in ValidateConfig
//   - Region: it is trimmed and then lowercased, so regions that differ only
//     in case are the same storage location. New does not lowercase it and
//     signs with SigV4 using the input with only leading and trailing white
//     space removed
//   - Bucket: leading and trailing white space is removed
//   - Prefix: leading and trailing slashes are removed
//
// The result is `s3-<64-character SHA-256 hexadecimal>`. This ID is a
// persistent format that is also stored in checkpoint file names, so changing
// the field order, the JSON field names, the normalization, the hash algorithm
// or the encoding also requires a checkpoint migration.
func ResolveDestinationID(cfg objectstorage.S3Config) (objectstorage.DestinationID, error) {
	region := normalizeRegion(cfg.Region)
	endpoint, err := normalizeEndpoint(cfg.Endpoint, region)
	if err != nil {
		return "", err
	}
	endpoint, err = canonicalDestinationEndpoint(endpoint)
	if err != nil {
		return "", err
	}

	identity := struct {
		Provider string `json:"provider"`
		Endpoint string `json:"endpoint"`
		Region   string `json:"region"`
		Bucket   string `json:"bucket"`
		Prefix   string `json:"prefix"`
	}{
		Provider: string(objectstorage.UploadTargetS3),
		Endpoint: endpoint,
		Region:   region,
		Bucket:   strings.TrimSpace(cfg.Bucket),
		Prefix:   strings.Trim(cfg.Prefix, "/"),
	}
	encoded, err := json.Marshal(identity)
	if err != nil {
		return "", err
	}
	digest := sha256.Sum256(encoded)
	return objectstorage.DestinationID(destinationIDPrefix + hex.EncodeToString(digest[:])), nil
}

// canonicalDestinationEndpointは、normalizeEndpointで検証済みのendpointについて
// 大文字小文字を区別しないschemeとhostをlowercaseへ揃えます。queryとfragmentは
// normalizeEndpointが拒否するため、identityには含まれません。
func canonicalDestinationEndpoint(endpoint string) (string, error) {
	parsed, err := url.Parse(endpoint)
	if err != nil {
		return "", err
	}
	parsed.Scheme = strings.ToLower(parsed.Scheme)
	parsed.Host = strings.ToLower(parsed.Host)
	return parsed.String(), nil
}
